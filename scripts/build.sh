#!/usr/bin/env bash
# Build the Cockroaches Cathisteria cartridge for one or both PRG32 targets.
#
#   scripts/build.sh            # esp32c6 and qemu
#   scripts/build.sh qemu       # one architecture
#
# Environment:
#   PRG32_REPO   path to the PRG32 firmware repository (default ../PRG32)
#   IDF_EXPORT   ESP-IDF export script sourced when riscv32-esp-elf-gcc is not
#                on PATH (default $HOME/esp-idf/export.sh)
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
prg32_repo="$(cd "${PRG32_REPO:-"$repo_dir/../PRG32"}" && pwd)"
name="cockroaches"
max_size=65536

if ! command -v riscv32-esp-elf-gcc >/dev/null 2>&1; then
  idf_export="${IDF_EXPORT:-$HOME/esp-idf/export.sh}"
  if [[ -f "$idf_export" ]]; then
    # shellcheck disable=SC1090
    source "$idf_export" >/dev/null 2>&1
  fi
fi
command -v riscv32-esp-elf-gcc >/dev/null 2>&1 || {
  echo "error: riscv32-esp-elf-gcc not found; source ESP-IDF export.sh first" >&2
  exit 2
}

archs=("$@")
if [[ ${#archs[@]} -eq 0 ]]; then
  archs=(esp32c6 qemu)
fi

build_dir="$repo_dir/build"
dist_dir="$repo_dir/dist"
mkdir -p "$build_dir" "$dist_dir"

# The 64 KiB adapter raises the host builder's RAM check to the firmware's
# default "extended" profile (see tools/prg32_cli_64.py).
prg32() {
  (cd "$prg32_repo" && PRG32_REPO="$prg32_repo" python3 "$repo_dir/tools/prg32_cli_64.py" "$@")
}

# 1. Generated sources must be current (they are committed; this is cheap).
python3 "$repo_dir/tools/gen_levels.py"
python3 "$repo_dir/tools/gen_assets.py"

# 2. AUDIO block: four PCM waves and seven instruments.
python3 "$prg32_repo/tools/prg32audio_pack.py" \
  "$repo_dir/audio/cc_audio.json" \
  --out "$build_dir/cc_audio.block"

for arch in "${archs[@]}"; do
  raw="$dist_dir/$name-$arch.raw.prg32"
  out="$dist_dir/$name-$arch.prg32"

  # 3. Portable ABI-table cartridge. A tiny wrapper selects the present
  #    strategy for the target (see CC_TARGET_QEMU in src/config.h).
  wrapper="$build_dir/cockroaches_$arch.c"
  {
    echo "/* Generated by scripts/build.sh for the $arch cartridge. */"
    if [[ "$arch" == "qemu" ]]; then echo "#define CC_TARGET_QEMU 1"; fi
    echo "#include \"$repo_dir/src/main.c\""
  } > "$wrapper"
  prg32 cartridge build "$wrapper" \
    --portable \
    --entry-prefix cockroaches \
    --name "$name" \
    --architecture "$arch" \
    --audio-block "$build_dir/cc_audio.block" \
    --build-dir "$build_dir" \
    --out "$raw"

  # 4. Store metadata trailer: metadata, icon, screenshot, colophon.
  prg32 store attach-metadata "$raw" \
    --out "$out" \
    --metadata "$repo_dir/metadata/metadata.json" \
    --icon "$repo_dir/assets/icon.png" \
    --screenshot "$repo_dir/assets/screenshot.png" \
    --colophon "$repo_dir/metadata/colophon.json" \
    --architecture "$arch"

  size=$(wc -c < "$out" | tr -d ' ')
  if (( size > max_size )); then
    echo "error: $out is $size bytes, above the $max_size byte cartridge limit" >&2
    exit 1
  fi
  echo "$out ($size bytes, $(( max_size - size )) bytes free)"
done
