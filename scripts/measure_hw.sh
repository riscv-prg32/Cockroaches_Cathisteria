#!/usr/bin/env bash
# Measure real frame times on an ESP32-C6 PRG32 board.
#
#   scripts/measure_hw.sh --slot cart3            # USB, the only connected board
#   scripts/measure_hw.sh --slot cart3 --url http://192.168.4.1
#
# Builds a CC_MEASURE cartridge (src/game.c: the game plays each of the 12
# levels for 240 frames by itself, with CC_TEST_GOD so Fed cannot die),
# uploads it to the slot you name (that slot is overwritten), starts it, waits
# for the run, then reads the PRG32 performance broker result and prints
# frames per second per level. The JSON is kept in build/measure/.
#
# pcb1 boards wire joystick DOWN to GPIO13 (native USB D+), so USB uploads
# and the device protocol do not work there: join the board to Wi-Fi in its
# setup menu and pass --url with the address it shows.
#
# Environment: PRG32_REPO (default ../PRG32); PRG32_PYTHON, a Python with
# pyserial for USB (default: the ESP-IDF Python environment, else python3).
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
prg32_repo="$(cd "${PRG32_REPO:-"$repo_dir/../PRG32"}" && pwd)"
slot="" url="" wait_s=240
while [[ $# -gt 0 ]]; do
  case "$1" in
    --slot) slot="$2"; shift 2 ;;
    --url) url="$2"; shift 2 ;;
    --wait) wait_s="$2"; shift 2 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
[[ -n "$slot" ]] || { echo "usage: $0 --slot cartN [--url http://board] [--wait seconds]" >&2; exit 2; }

py="${PRG32_PYTHON:-}"
if [[ -z "$py" ]]; then
  py="$(ls "$HOME"/.espressif/python_env/*/bin/python 2>/dev/null | tail -1 || true)"
  [[ -n "$py" ]] || py=python3
fi
if ! command -v riscv32-esp-elf-gcc >/dev/null 2>&1; then
  tc="$(ls -d "$HOME"/.espressif/tools/riscv32-esp-elf/*/riscv32-esp-elf/bin 2>/dev/null | tail -1 || true)"
  [[ -n "$tc" ]] && export PATH="$tc:$PATH"
fi

out="$repo_dir/build/measure"
mkdir -p "$out"
python3 "$prg32_repo/tools/prg32audio_pack.py" "$repo_dir/audio/cc_audio.json" --out "$out/cc_audio.block" >/dev/null
cat > "$out/cockroaches_measure.c" <<EOF
/* Generated by scripts/measure_hw.sh: hardware frame-time benchmark. */
#define CC_MEASURE 1
#define CC_TEST_GOD 1
#include "$repo_dir/src/main.c"
EOF
prg32() { (cd "$prg32_repo" && "$py" -m prg32 "$@"); }
prg32 cartridge build "$out/cockroaches_measure.c" --portable --entry-prefix cockroaches \
  --name cockroaches-measure --architecture esp32c6 --cart-ram-kib 128 \
  --audio-block "$out/cc_audio.block" --build-dir "$out/esp32c6" \
  --out "$out/measure-esp32c6.prg32" | grep -E "code=|OK" || true

target=()
[[ -n "$url" ]] && target=(--url "$url")
echo "uploading to $slot (this slot is overwritten) and starting the run"
prg32 esp32c6 upload "$out/measure-esp32c6.prg32" ${target[@]+"${target[@]}"} --slot "$slot" --command run
echo "waiting ${wait_s}s for 12 levels x 240 frames..."
sleep "$wait_s"
json="$out/performance-$(date +%Y%m%d-%H%M%S).json"
prg32 esp32c6 performance ${target[@]+"${target[@]}"} --out "$json"
python3 - "$json" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
rows = data.get("screen_summaries") or []
print(f"{'level':6s} {'fps':>6s} {'mean ms':>8s} {'p95 ms':>7s} {'max ms':>7s} {'draw ms':>8s} {'present ms':>10s}")
ms = lambda v: f"{v / 1000:.1f}" if isinstance(v, (int, float)) else "?"
for r in rows:
    mean = r.get("frame_us_mean")
    fps = f"{1e6 / mean:.1f}" if mean else "?"
    print(f"{r.get('screen_name', '?'):6s} {fps:>6s} {ms(mean):>8s} {ms(r.get('frame_us_p95')):>7s} "
          f"{ms(r.get('frame_us_max')):>7s} {ms(r.get('draw_us_mean')):>8s} {ms(r.get('present_us_mean')):>10s}")
if not rows:
    print(json.dumps(data, indent=1)[:3000])
PY
echo "result: $json"
